export const CITIES: CityOption[] = RAW.map(([city, region, lat, lng]) => ({ city, region, lat, lng }));

export function cityLabel(city: CityOption): string {
  return `${city.city}, ${city.region}`;
}

export function searchCities(query: string, limit = 8): CityOption[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  return CITIES.filter((city) => cityLabel(city).toLowerCase().includes(q))
    .sort((a, b) => {
      const aStart = a.city.toLowerCase().startsWith(q) ? 0 : 1;
      const bStart = b.city.toLowerCase().startsWith(q) ? 0 : 1;
      return aStart - bStart || a.city.localeCompare(b.city) || a.region.localeCompare(b.region);
    })
    .slice(0, limit);
}
